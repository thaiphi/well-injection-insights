import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {syntheticActuals,freezeForecast,planningCase} from '../dist/planning.js';
import {planningFixture} from '../dist/planningFixture.js';
import {INJECTORS} from '../dist/engineering.js';
import {validatePublicArtifact} from '../dist/publicArtifact.js';
import {buildExhibit,exhibitCsv} from '../dist/exhibit.js';
import {exhibitSvg} from '../dist/exhibitSvg.js';
import {verifyArtifact} from './artifact-files.mjs';
const actuals=syntheticActuals(),frozen=freezeForecast(actuals),controls={newWellStart:'2026-04',expansionMonth:'2026-08',expansionStbd:2000};
const verified=await verifyArtifact('data/explorer');
const storedPin=JSON.parse(await readFile('data/explorer-pin.json','utf8'));
if(JSON.stringify(verified.pin)!==JSON.stringify(storedPin)) throw new Error('Explorer artifact differs from its pinned version; re-import after review');
const publicArtifact=await validatePublicArtifact(verified.artifact);
const rows=planningCase(frozen,actuals,INJECTORS,controls.newWellStart,controls.expansionMonth,controls.expansionStbd);
const exhibit=await buildExhibit({frozen,rows,injectors:INJECTORS,controls,publicArtifact,planningFixture:planningFixture(controls.newWellStart)});
await mkdir('exhibits',{recursive:true});
await writeFile('exhibits/default.json',JSON.stringify(exhibit,null,2)+'\n');await writeFile('exhibits/default.csv',exhibitCsv(exhibit));
await writeFile('exhibits/default.svg',exhibitSvg(exhibit));
console.log(`Exported ${rows.length} planning months + ${publicArtifact.injectionMonthly.length} public rows; SHA256 ${exhibit.contentSha256}`);
